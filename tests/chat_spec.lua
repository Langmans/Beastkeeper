-- Sending chat on the player's next input (Core\Chat.lua): WoW: Forever only lets an addon send
-- chat inside a hardware event, so a message waits for the next key press or click in the game
-- world, for at most ten seconds.

---The frame that watches keys while a message waits.
local function keyFrame()
    return _G.KennelChatKeys
end

describe("sending on the next input", function()
    it("waits for a key press and sends inside it, once", function()
        local client = NewClient():login()
        client.Kennel:SendOnInput("feeds Fluffy.", "EMOTE")
        client:advance(3)
        assert.are.same({}, client.chatSent, "nothing from an event or a timer")
        client:pressKey("W")
        assert.are.same({ { "feeds Fluffy.", "EMOTE" } }, client.chatSent)
        client:pressKey("W")
        assert.are.equal(1, #client.chatSent)
    end)

    it("sends on a click in the game world as well", function()
        local client = NewClient():login()
        client.Kennel:SendOnInput("feeds Fluffy.", "EMOTE")
        client:clickWorld()
        client:clickWorld()
        assert.are.equal(1, #client.chatSent)
    end)

    it("shows the key frame only while a message waits, and passes every key on", function()
        local client = NewClient():login()
        local keys = keyFrame(client)
        assert.is_false(keys.shown)
        assert.is_true(keys.propagate)
        client.Kennel:SendOnInput("x", "EMOTE")
        assert.is_true(keys.shown)
        client:pressKey()
        assert.is_false(keys.shown)
    end)

    it("loaded in combat, watches keys only once combat ends; clicks still send", function()
        local client = NewClient({ inCombat = true }):login()
        local keys = keyFrame(client)
        client.Kennel:SendOnInput("x", "EMOTE")
        assert.is_false(keys.shown, "a shown frame without propagation would swallow keys")
        client:clickWorld()
        assert.are.equal(1, #client.chatSent)
        client:leaveCombat()
        client.Kennel:SendOnInput("y", "EMOTE")
        assert.is_true(keys.shown)
        client:pressKey()
        assert.are.equal(2, #client.chatSent)
    end)

    it("drops a message not sent within ten seconds", function()
        local client = NewClient():login()
        client.Kennel:SendOnInput("x", "EMOTE")
        client:advance(9.5)
        client:pressKey()
        assert.are.equal(1, #client.chatSent, "just in time")
        client.Kennel:SendOnInput("y", "EMOTE")
        client:advance(11)
        assert.is_false(keyFrame(client).shown, "the timeout hides the key frame")
        client:pressKey()
        assert.are.equal(1, #client.chatSent)
    end)

    it("replaces a message still waiting with a newer one", function()
        local client = NewClient():login()
        client.Kennel:SendOnInput("first", "EMOTE")
        client:advance(2)
        client.Kennel:SendOnInput("second", "EMOTE")
        client:advance(9)
        client:pressKey()
        assert.are.same({ { "second", "EMOTE" } }, client.chatSent)
    end)

    it("drops the message when the client locks addon chat at that moment", function()
        local client = NewClient():login()
        client.Kennel:SendOnInput("x", "EMOTE")
        client.chatLocked = true
        client:pressKey()
        assert.are.same({}, client.chatSent)
    end)

    it("goes through MessageQueue's queue when that is loaded, without the key frame", function()
        local client = NewClient({ messageQueue = true }):login()
        client.Kennel:SendOnInput("first", "EMOTE")
        client.Kennel:SendOnInput("second", "EMOTE")
        assert.is_false(keyFrame(client).shown)
        client:runMessageQueue()
        assert.are.same({ { "second", "EMOTE" } }, client.chatSent, "only the newer one")
        client.Kennel:SendOnInput("late", "EMOTE")
        client:advance(11):runMessageQueue()
        assert.are.equal(1, #client.chatSent, "a late run after the timeout sends nothing")
    end)

    it("sends through the old global on a client without C_ChatInfo", function()
        local client = NewClient({ oldChatAPI = true }):login()
        client.Kennel:SendOnInput("x", "EMOTE")
        client:pressKey()
        assert.are.same({ { "x", "EMOTE" } }, client.chatSent)
    end)
end)
