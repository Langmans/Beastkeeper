-- OutOfCombat: what may not run in combat (secure frames, macros) runs now, or once combat ends.

describe("OutOfCombat", function()
    it("runs at once outside combat", function()
        local client = NewClient():login()
        local ran = spy.new(function() end)
        client.Kennel:OutOfCombat("x", ran)
        assert.spy(ran).was.called(1)
    end)

    it("waits in combat and runs once combat ends, the last one asked per key", function()
        local client = NewClient():login():enterCombat()
        local first, last, other = spy.new(function() end), spy.new(function() end), spy.new(function() end)
        client.Kennel:OutOfCombat("x", first)
        client.Kennel:OutOfCombat("x", last)
        client.Kennel:OutOfCombat("y", other)
        assert.spy(last).was_not.called()
        client:leaveCombat()
        assert.spy(first).was_not.called()
        assert.spy(last).was.called(1)
        assert.spy(other).was.called(1)
        client:enterCombat():leaveCombat()
        assert.spy(last).was.called(1)
    end)
end)
